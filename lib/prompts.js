function buildPrompt(taskKey, payload, opts = {}) {
  const task = TASKS[taskKey];
  if (!task) throw new Error(`Unknown task: ${taskKey}`);

  const boost = opts.retry
    ? `\n\n${RETRY_BOOST[taskKey] || RETRY_BOOST.default}`
    : '';

  return {
    // systemInstruction لازم يكون Content object، مش نص عادي
    systemInstruction: {
      role: 'system',
      parts: [{ text: NEUTRAL_CORE }],
    },
    contents: [
      {
        role: 'user',
        parts: [
          { text: `${task.instruction}${boost}\n\n---\nالبيانات:\n${JSON.stringify(payload, null, 2)}` },
        ],
      },
    ],
    generationConfig: {
      temperature: 0.7,
      // 1024 كان سقف مبتور — الموديل بيقطع بنص الجملة.
      // التحليل الكامل (جدول + مقايضات + سؤال) بيحتاج أضعاف.
      maxOutputTokens: 8192,
      // بدوّر بالتفكير قبل ما يكتب. بدونه الموديل بيرد سطحياً
      // وبيطلّع كلام عام مثل «الأمر بيعتمد عليك».
      // ملاحظة: thinkingConfig لازم جوّا generationConfig — لو حُطّ
      // بالأعلى، Gemini بيرجّع 400 فطير.
      thinkingConfig: { thinkingBudget: 2048 },
      responseMimeType: 'application/json',
      responseSchema: task.schema,
    },
  };
}

